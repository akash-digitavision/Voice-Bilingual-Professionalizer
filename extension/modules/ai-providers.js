/**
 * AI Provider Abstraction Layer (Phase 8, 11, 12)
 * Normalized bilingual refinement across OpenAI, Gemini, and Custom Endpoints.
 */

export const ERROR_CODES = {
  AUTH_ERROR: 'AUTH_ERROR',
  INVALID_REQUEST: 'INVALID_REQUEST',
  RATE_LIMIT: 'RATE_LIMIT',
  QUOTA_EXCEEDED: 'QUOTA_EXCEEDED',
  TIMEOUT: 'TIMEOUT',
  NETWORK_ERROR: 'NETWORK_ERROR',
  SERVER_ERROR: 'SERVER_ERROR',
  MODEL_UNAVAILABLE: 'MODEL_UNAVAILABLE',
  UNKNOWN_ERROR: 'UNKNOWN_ERROR'
};

export function getSystemPrompt(tone = 'professional', conciseness = 'balanced') {
  return `You are a professional bilingual language refinement assistant.

The user's input may be:
- Bangla
- English
- Banglish (Bangla written in English script or mixed phonetic script)
- mixed Bangla/English codeswitching
- rough speech-to-text with spoken hesitations
- grammatically incorrect
- incomplete
- informal

Your job is to understand the intended meaning and produce two polished, ready-to-use versions:

1. Natural professional Bangla:
   - Must sound authentic, respectful, and culturally natural to a Bangladeshi professional.
   - Do NOT produce mechanical word-for-word translation.
   - Use standard modern formal/semi-formal Bengali (চলিত রীতি).

2. Natural professional English:
   - Must sound fluent, crisp, and executive.
   - Do NOT produce literal Bangla-to-English translation.

Core Rules:
- Preserve the original meaning and factual details strictly.
- Do NOT invent facts, names, dates, numbers, policies, or technical commitments.
- Correct grammar, spelling, and sentence structure.
- Remove obvious voice-transcription artifacts, filler words, or stutters.
- Tone target: ${tone.toUpperCase()} (Polite, clear, respectful, helpful, confident).
- Length target: ${conciseness.toUpperCase()} (Expressive yet concise; never add filler just to pad length).
- Do NOT mention that this text was generated by AI.
- Do NOT include markdown code blocks or explanations outside the JSON.

CRITICAL: Return ONLY a valid JSON object strictly matching this schema:
{
  "bangla": "পেশাদার বাংলা রূপান্তর...",
  "english": "Professional English refinement..."
}`;
}

export async function generateBilingualOutput(transcript, settings = {}) {
  const provider = settings.provider || 'openai';
  const tone = settings.tone || 'professional';
  const conciseness = settings.conciseness || 'balanced';

  try {
    if (provider === 'openai') {
      return await callOpenAI(transcript, settings, tone, conciseness);
    } else if (provider === 'gemini') {
      return await callGemini(transcript, settings, tone, conciseness);
    } else if (provider === 'custom') {
      return await callCustomEndpoint(transcript, settings, tone, conciseness);
    } else {
      throw { code: ERROR_CODES.INVALID_REQUEST, message: `Unsupported provider: ${provider}` };
    }
  } catch (err) {
    // Check fallback policy if enabled and alternative is available
    if (settings.enableFallback && provider === 'openai' && settings.geminiKey) {
      console.warn('Primary OpenAI provider failed, attempting fallback to Gemini:', err);
      try {
        return await callGemini(transcript, settings, tone, conciseness);
      } catch (fallbackErr) {
        throw normalizeError(fallbackErr);
      }
    }
    throw normalizeError(err);
  }
}

async function callOpenAI(transcript, settings, tone, conciseness) {
  const apiKey = settings.openaiKey;
  if (!apiKey) {
    throw {
      code: ERROR_CODES.AUTH_ERROR,
      message: 'OpenAI API Key is missing. Please configure it in Extension Options.'
    };
  }

  const model = settings.openaiModel || 'gpt-4o-mini';
  const endpoint = 'https://api.openai.com/v1/chat/completions';

  const response = await fetch(endpoint, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${apiKey.trim()}`
    },
    body: JSON.stringify({
      model: model,
      temperature: 0.3,
      response_format: { type: 'json_object' },
      messages: [
        { role: 'system', content: getSystemPrompt(tone, conciseness) },
        { role: 'user', content: transcript }
      ]
    })
  });

  if (!response.ok) {
    const errorBody = await response.json().catch(() => ({}));
    if (response.status === 401) {
      throw { code: ERROR_CODES.AUTH_ERROR, message: 'Invalid OpenAI API Key.' };
    } else if (response.status === 429) {
      throw { code: ERROR_CODES.RATE_LIMIT, message: 'OpenAI rate limit or quota exceeded.' };
    } else {
      throw {
        code: ERROR_CODES.SERVER_ERROR,
        message: errorBody.error?.message || `OpenAI request failed (HTTP ${response.status})`
      };
    }
  }

  const data = await response.json();
  const rawContent = data.choices?.[0]?.message?.content;
  return parseStructuredResult(rawContent);
}

async function callGemini(transcript, settings, tone, conciseness) {
  const apiKey = settings.geminiKey;
  if (!apiKey) {
    throw {
      code: ERROR_CODES.AUTH_ERROR,
      message: 'Gemini API Key is missing. Please configure it in Extension Options.'
    };
  }

  let primaryModel = settings.geminiModel || 'gemini-3.8-flash';
  if (primaryModel === 'gemini-2.5-flash') {
    primaryModel = 'gemini-3.8-flash';
  }

  // Model fallback chain: primary model first, followed by valid current models
  const candidateModels = [primaryModel];
  if (primaryModel !== 'gemini-3.8-flash') candidateModels.push('gemini-3.8-flash');
  if (primaryModel !== 'gemini-3.1-flash-lite') candidateModels.push('gemini-3.1-flash-lite');

  let lastErr = null;

  for (const model of candidateModels) {
    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey.trim()}`;

    try {
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          systemInstruction: {
            parts: [{ text: getSystemPrompt(tone, conciseness) }]
          },
          contents: [
            {
              role: 'user',
              parts: [{ text: transcript }]
            }
          ],
          generationConfig: {
            responseMimeType: 'application/json',
            temperature: 0.3
          }
        })
      });

      if (!response.ok) {
        const errorBody = await response.json().catch(() => ({}));
        if (response.status === 400 || response.status === 403) {
          throw { code: ERROR_CODES.AUTH_ERROR, message: 'Invalid Gemini API key or unauthorized model access.' };
        } else if (response.status === 429) {
          throw { code: ERROR_CODES.RATE_LIMIT, message: 'Gemini quota or rate limit exceeded.' };
        } else if (response.status === 404 || response.status === 503) {
          lastErr = {
            code: ERROR_CODES.MODEL_UNAVAILABLE,
            message: errorBody.error?.message || `Model ${model} unavailable (HTTP ${response.status})`
          };
          continue; // try next candidate model
        } else {
          throw {
            code: ERROR_CODES.SERVER_ERROR,
            message: errorBody.error?.message || `Gemini request failed (HTTP ${response.status})`
          };
        }
      }

      const data = await response.json();
      const rawContent = data.candidates?.[0]?.content?.parts?.[0]?.text;
      return parseStructuredResult(rawContent);
    } catch (e) {
      if (e.code === ERROR_CODES.AUTH_ERROR || e.code === ERROR_CODES.RATE_LIMIT) {
        throw e;
      }
      lastErr = e;
    }
  }

  throw lastErr || { code: ERROR_CODES.SERVER_ERROR, message: 'Gemini refinement request failed.' };
}

async function callCustomEndpoint(transcript, settings, tone, conciseness) {
  const endpoint = settings.customEndpoint;
  if (!endpoint) {
    throw {
      code: ERROR_CODES.INVALID_REQUEST,
      message: 'Custom endpoint URL is required.'
    };
  }

  const headers = { 'Content-Type': 'application/json' };
  if (settings.customKey) {
    headers['Authorization'] = `Bearer ${settings.customKey.trim()}`;
  }

  const response = await fetch(endpoint, {
    method: 'POST',
    headers,
    body: JSON.stringify({
      model: settings.customModel || 'default',
      temperature: 0.3,
      messages: [
        { role: 'system', content: getSystemPrompt(tone, conciseness) },
        { role: 'user', content: transcript }
      ]
    })
  });

  if (!response.ok) {
    throw { code: ERROR_CODES.SERVER_ERROR, message: `Custom endpoint returned status ${response.status}` };
  }

  const data = await response.json();
  const rawContent = data.choices?.[0]?.message?.content || data.text;
  return parseStructuredResult(rawContent);
}

function parseStructuredResult(raw) {
  if (!raw) {
    throw { code: ERROR_CODES.SERVER_ERROR, message: 'Empty response received from AI model.' };
  }

  try {
    // Clean any markdown code ticks if present
    const cleaned = raw.replace(/^```json\s*/i, '').replace(/\s*```$/i, '').trim();
    const parsed = JSON.parse(cleaned);

    if (!parsed.bangla || !parsed.english) {
      throw new Error('Response missing bangla or english fields');
    }

    return {
      bangla: parsed.bangla.trim(),
      english: parsed.english.trim()
    };
  } catch (err) {
    console.error('Failed to parse AI response JSON:', raw, err);
    throw {
      code: ERROR_CODES.SERVER_ERROR,
      message: 'Unable to parse bilingual output from model. Please try again.'
    };
  }
}

function normalizeError(err) {
  if (err && err.code && ERROR_CODES[err.code]) {
    return err;
  }
  return {
    code: ERROR_CODES.UNKNOWN_ERROR,
    message: err?.message || 'An unexpected error occurred during AI refinement.'
  };
}
